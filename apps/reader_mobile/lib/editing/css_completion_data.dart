bool cssHasLengthValues(String property) => RegExp(
  r'^(font-size|line-height|letter-spacing|word-spacing|text-indent|vertical-align|width|height|min-(width|height)|max-(width|height)|margin(-.*)?|padding(-.*)?|inset(-.*)?|top|right|bottom|left|gap|row-gap|column-(gap|width)|border-(width|radius|spacing)|outline-(width|offset)|text-(underline-offset|decoration-thickness)|flex-basis)$',
).hasMatch(property);

List<String> cssValuesFor(String property) {
  final colors = property == 'color' || property.endsWith('-color');
  return [
    ...?cssKeywordValues[property],
    if (colors || property == 'background') ...[
      'currentColor',
      'transparent',
      '#333333',
      '#ffffff',
      'black',
      'white',
    ],
    if (cssHasLengthValues(property)) ...[
      '0',
      '1em',
      '1.5em',
      '2em',
      '1rem',
      '16px',
      '100%',
    ],
    if (RegExp(
      r'^(margin|width|height|min-|max-|inset|top$|left$|right$|bottom$|flex-basis)',
    ).hasMatch(property))
      'auto',
    if (property.startsWith('max-')) 'none',
    if (['opacity', 'flex-grow', 'flex-shrink'].contains(property)) ...[
      '0',
      '0.5',
      '1',
    ],
    if (['z-index', 'column-count'].contains(property)) 'auto',
    if ([
      'z-index',
      'column-count',
      'orphans',
      'widows',
    ].contains(property)) ...[
      '1',
      '2',
      '3',
    ],
    if (property == 'src') ...['url()', 'local()'],
    if (property == 'background-image' || property == 'list-style-image') ...[
      'none',
      'url()',
    ],
    if (property == 'border' ||
        property == 'outline' ||
        property == 'column-rule') ...[
      'none',
      '1px solid currentColor',
    ],
    if (property.endsWith('shadow')) ...['none', '0 1px 2px #000000'],
    if (property == 'content') ...[
      'none',
      'normal',
      'open-quote',
      'close-quote',
      'attr()',
    ],
    if (property == 'transform') ...[
      'none',
      'translate()',
      'scale()',
      'rotate()',
    ],
    'inherit',
    'initial',
    'unset',
    'revert',
    '!important',
  ];
}
